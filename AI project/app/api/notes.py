"""
StudyMate AI - Notes API Endpoints
"""
import json
from fastapi import APIRouter, HTTPException, Response
from typing import Optional
from app.database import get_connection
from app.models import GenerateNotesRequest
from app.services.ai_generator import generate_notes_hybrid

router = APIRouter(prefix="/api/notes", tags=["Notes"])

@router.post("/generate")
def generate_notes_endpoint(req: GenerateNotesRequest):
    """Generates structured study notes from an existing document or custom text."""
    conn = get_connection()
    cursor = conn.cursor()

    text_to_process = ""
    title = req.title or "Study Notes"
    subject = req.subject or "General Studies"
    doc_id = req.document_id

    if doc_id:
        cursor.execute("SELECT * FROM documents WHERE id = ?", (doc_id,))
        doc = cursor.fetchone()
        if not doc:
            conn.close()
            raise HTTPException(status_code=404, detail="Document not found")
        text_to_process = doc['content']
        title = doc['title']
        subject = doc['subject']
    elif req.custom_text and req.custom_text.strip():
        text_to_process = req.custom_text.strip()
    else:
        conn.close()
        raise HTTPException(status_code=400, detail="Provide either document_id or custom_text.")

    notes_data = generate_notes_hybrid(text_to_process, title, subject)

    cursor.execute("""
    INSERT INTO notes (
        document_id, title, summary, key_concepts,
        cheat_sheet, flashcards, mindmap, glossary
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        doc_id, notes_data['title'], notes_data['summary'],
        json.dumps(notes_data['key_concepts']),
        json.dumps(notes_data['cheat_sheet']),
        json.dumps(notes_data['flashcards']),
        notes_data['mindmap'],
        json.dumps(notes_data['glossary'])
    ))
    notes_id = cursor.lastrowid
    conn.commit()
    conn.close()

    notes_data["id"] = notes_id
    notes_data["document_id"] = doc_id
    return notes_data

@router.get("")
def list_notes():
    """Lists all generated notes summaries."""
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
    SELECT n.id, n.document_id, n.title, n.summary, n.created_at,
           d.subject, d.sdg_target
    FROM notes n
    LEFT JOIN documents d ON n.document_id = d.id
    ORDER BY n.created_at DESC
    """)
    notes = [dict(row) for row in cursor.fetchall()]
    conn.close()
    return {"notes": notes}

@router.get("/{notes_id}")
def get_note(notes_id: int):
    """Retrieves full details of a specific note."""
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM notes WHERE id = ?", (notes_id,))
    row = cursor.fetchone()
    conn.close()
    if not row:
        raise HTTPException(status_code=404, detail="Notes not found")

    d = dict(row)
    d['key_concepts'] = json.loads(d['key_concepts'])
    d['cheat_sheet'] = json.loads(d['cheat_sheet'])
    d['flashcards'] = json.loads(d['flashcards'])
    d['glossary'] = json.loads(d['glossary'])
    return d

@router.get("/{notes_id}/export/{format_type}")
def export_note(notes_id: int, format_type: str):
    """Exports notes as Markdown (.md) or JSON (.json)."""
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM notes WHERE id = ?", (notes_id,))
    row = cursor.fetchone()
    conn.close()
    if not row:
        raise HTTPException(status_code=404, detail="Notes not found")

    d = dict(row)
    concepts = json.loads(d['key_concepts'])
    cheat_sheet = json.loads(d['cheat_sheet'])
    flashcards = json.loads(d['flashcards'])
    glossary = json.loads(d['glossary'])

    if format_type.lower() == "json":
        data = {
            "title": d['title'],
            "summary": d['summary'],
            "key_concepts": concepts,
            "cheat_sheet": cheat_sheet,
            "flashcards": flashcards,
            "mindmap": d['mindmap'],
            "glossary": glossary
        }
        return Response(content=json.dumps(data, indent=2), media_type="application/json")
    
    md_lines = [
        f"# {d['title']}",
        f"*Generated by StudyMate AI*\n",
        "## 📌 Executive Summary",
        f"{d['summary']}\n",
        "## 🧠 Key Concepts & Analogies"
    ]
    for c in concepts:
        md_lines.append(f"### {c.get('concept', '')}")
        md_lines.append(f"- **Definition**: {c.get('definition', '')}")
        md_lines.append(f"- **Analogy**: {c.get('analogy', '')}")
        md_lines.append(f"- **Application**: {c.get('real_world_application', '')}")
        md_lines.append(f"- **Practical Insight**: {c.get('practical_insight', '')}\n")

    md_lines.append("## ⚡ Cheat Sheet & Core Rules")
    for cs in cheat_sheet:
        md_lines.append(f"- **{cs.get('topic', '')}**: `{cs.get('rules_or_formula', '')}`")
        md_lines.append(f"  *{cs.get('quick_tip', '')}*")

    md_lines.append("\n## 🗂️ Active Recall Flashcards")
    for fc in flashcards:
        md_lines.append(f"- **Q [{fc.get('difficulty', '')}]**: {fc.get('front', '')}")
        md_lines.append(f"  **A**: {fc.get('back', '')}\n")

    md_lines.append("## 🗺️ Mind Map")
    md_lines.append("```mermaid")
    md_lines.append(d['mindmap'])
    md_lines.append("```\n")

    md_lines.append("## 📖 High-Yield Glossary")
    for g in glossary:
        md_lines.append(f"- **{g.get('term', '')}**: {g.get('definition', '')}")

    return Response(
        content="\n".join(md_lines),
        media_type="text/markdown",
        headers={"Content-Disposition": f'attachment; filename="{d["title"].replace(" ", "_")}_Notes.md"'}
    )
